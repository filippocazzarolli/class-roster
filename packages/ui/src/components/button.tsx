function Button({
  className,
  variant = "default",
  size = "default",
  render,
  nativeButton,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  /*
   * `nativeButton` dedotto da ciò che si sta rendendo davvero.
   *
   * Base UI assume un `<button>` nativo, e un `render={<Link/>}` produce invece un `<a>`:
   * senza correggere l'assunzione il componente tiene le semantiche del bottone — fra cui
   * l'invio del form — su un elemento che non le ha, e lo segnala in console.
   *
   * La deduzione sta qui e non in ogni chiamata perché è una proprietà dell'elemento
   * passato, non una decisione di chi usa il bottone: chiedergliela significherebbe
   * scoprire l'unica volta che se la dimentica. Chi ha un caso che questa regola non
   * copre — un `render` come funzione, di cui non si può ispezionare il risultato —
   * passa `nativeButton` esplicitamente e vince sulla deduzione.
   */
  const rendeUnBottoneNativo =
    render === undefined ||
    (React.isValidElement(render) && render.type === "button")

  return (
    <ButtonPrimitive
      data-slot="button"
      render={render}
      nativeButton={nativeButton ?? rendeUnBottoneNativo}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

